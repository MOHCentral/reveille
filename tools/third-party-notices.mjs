// Reveille is GPL-3.0-only, and the permissive licences it links against (MIT, BSD, ISC, Apache,
// MPL) all require their own notice to travel with the binary. This writes that notice from the
// locked graph rather than from a hand-kept list, so a dependency change cannot silently drop an
// attribution.
//
// Only what the installer actually ships is listed: the normal-dependency graph of the Tauri shell
// for the Windows target. Build scripts and proc macros run on the build machine and are not
// distributed, so including them would overstate what the file covers.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repository = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = "x86_64-pc-windows-msvc";
const OUTPUT = join(repository, "crates", "reveille-app", "THIRD-PARTY-NOTICES.md");
// `bundle.resources` is validated when `tauri-build` compiles the shell, not when the bundler
// runs, so naming the file in tauri.conf.json would break every `cargo build` that has not
// generated it first. It belongs to packaging alone, which is what this overlay is for.
const PACKAGING_CONFIG = join(repository, "crates", "reveille-app", "notices.conf.json");
const LICENCE_FILE = /^(licen[cs]e|copying|notice|unlicense)/i;

function cargo(args) {
  return execFileSync("cargo", args, {
    cwd: repository,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
}

const metadata = JSON.parse(cargo(["metadata", "--format-version", "1", "--locked"]));
const packages = new Map(metadata.packages.map((p) => [`${p.name} ${p.version}`, p]));
const workspace = new Set(metadata.workspace_members);

// `--edges normal` drops build, dev, and proc-macro edges; `--target` drops the crates compiled
// only for other platforms.
const shipped = new Set(
  cargo([
    "tree",
    "--package",
    "reveille-app",
    "--target",
    TARGET,
    "--edges",
    "normal",
    "--prefix",
    "none",
    "--format",
    "{p}",
    "--locked",
  ])
    .split("\n")
    // `{p}` prints `name vX.Y.Z`, followed by a path or `(*)` for an already-listed subtree.
    .map((line) => /^(\S+) v(\S+)/.exec(line.trim()))
    .filter(Boolean)
    .map(([, name, version]) => `${name} ${version}`),
);

const entries = [];
for (const key of shipped) {
  const [name, version] = key.split(" ");
  const pkg = packages.get(`${name} ${version}`);
  if (!pkg) {
    throw new Error(`${key}: present in the dependency tree but not in cargo metadata`);
  }
  if (workspace.has(pkg.id)) {
    continue;
  }
  const root = dirname(pkg.manifest_path);
  const texts = [];
  for (const file of readdirSync(root).sort()) {
    if (!LICENCE_FILE.test(file) || !statSync(join(root, file)).isFile()) {
      continue;
    }
    const text = readFileSync(join(root, file), "utf8").replace(/\r\n/g, "\n").trimEnd();
    if (text) {
      texts.push({ file, text, digest: createHash("sha256").update(text).digest("hex") });
    }
  }
  entries.push({ name, version, licence: pkg.license ?? null, texts });
}
entries.sort((a, b) => a.name.localeCompare(b.name, "en") || a.version.localeCompare(b.version, "en"));

// The Apache-2.0 and Unicode texts are byte-identical across hundreds of crates. Printing each
// copy would make the file unreadable and unreviewable, so identical texts are shared.
const shared = new Map();
for (const entry of entries) {
  for (const { file, text, digest } of entry.texts) {
    let record = shared.get(digest);
    if (!record) {
      record = { file, text, used: [] };
      shared.set(digest, record);
    }
    record.used.push(`${entry.name} ${entry.version}`);
  }
}
const texts = [...shared.values()].sort((a, b) => b.used.length - a.used.length || a.used[0].localeCompare(b.used[0], "en"));
const anchors = new Map([...texts.entries()].map(([index, record]) => [record, index + 1]));

const missing = entries.filter((entry) => entry.texts.length === 0);

const lines = [];
lines.push("# Third-party notices");
lines.push("");
lines.push(
  "Reveille itself is licensed GPL-3.0-only; see `LICENSE`. The Windows application also contains",
);
lines.push(
  `the ${entries.length} components below, each under its own licence. This file is generated by`,
);
lines.push(
  "`just notices` from the locked dependency graph for `" +
    TARGET +
    "` and covers only code that is distributed, not build-time tooling.",
);
lines.push("");
lines.push("## Components");
lines.push("");
lines.push("| Component | Version | Licence | Text |");
lines.push("| --- | --- | --- | --- |");
for (const entry of entries) {
  const references = entry.texts
    .map(({ digest }) => anchors.get(shared.get(digest)))
    .map((index) => `[${index}](#licence-text-${index})`)
    .join(", ");
  lines.push(
    `| \`${entry.name}\` | ${entry.version} | ${entry.licence ?? "see text"} | ${references || "—"} |`,
  );
}
if (missing.length > 0) {
  lines.push("");
  lines.push(
    "The published crates for " +
      missing.map((entry) => `\`${entry.name}\``).join(", ") +
      " carry no licence file of their own; the licence column states the terms their authors declared.",
  );
}
lines.push("");
lines.push("## Licence texts");
for (const record of texts) {
  const index = anchors.get(record);
  lines.push("");
  lines.push(`### Licence text ${index}`);
  lines.push("");
  lines.push(`From \`${record.file}\`, applying to: ${record.used.map((used) => `\`${used}\``).join(", ")}.`);
  lines.push("");
  lines.push("```");
  lines.push(record.text.replace(/```/g, "` ` `"));
  lines.push("```");
}
lines.push("");

writeFileSync(OUTPUT, lines.join("\n"), "utf8");
writeFileSync(
  PACKAGING_CONFIG,
  `${JSON.stringify({ bundle: { resources: ["THIRD-PARTY-NOTICES.md"] } }, null, 2)}\n`,
  "utf8",
);
console.log(
  `${entries.length} distributed components, ${texts.length} distinct licence texts -> ${OUTPUT.slice(repository.length + 1)}`,
);
